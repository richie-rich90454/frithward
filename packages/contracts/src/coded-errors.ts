export type CodedErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES];

export const ALL_ERROR_CODES: readonly CodedErrorCode[] = Object.values(ERROR_CODES);

export class CodedError extends Error {
    public readonly code: CodedErrorCode;
    public readonly params: Readonly<Record<string, string | number>>;

    public constructor(
        code: CodedErrorCode,
        message: string,
        params: Readonly<Record<string, string | number>> = {},
        options?: { cause?: unknown },
    ) {
        super(message, options);
        this.name = "CodedError";
        this.code = code;
        this.params = params;
    }
}
